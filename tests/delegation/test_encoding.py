"""Encoding tests — golden vectors produced with viem 2.x.

Every vector here was generated by the reference viem stack (the same one
openclawnch ships) and proves the pure-Python encoders are byte-for-byte
compatible with it. If any of these break, redemption calldata would diverge
from what the on-chain DelegationManager expects.
"""

from __future__ import annotations

import pytest
from eth_account import Account
from eth_account.messages import encode_typed_data
from eth_utils import keccak

from clawmes.delegation import encoding as E
from clawmes.delegation.types import ROOT_AUTHORITY, Caveat, SignedDelegation, UnsignedDelegation

# The canonical fixture used across vectors.
_DELEGATE = "0x2222222222222222222222222222222222222222"
_DELEGATOR = "0x3333333333333333333333333333333333333333"
_ENFORCER = "0x92Bf12322527cAA612fd31a0e810472BBB106A8F"
_TERMS = "0x" + "00" * 31 + "64"


def _signed(sig: str = "0x" + "aa" * 65) -> SignedDelegation:
    return SignedDelegation(
        delegate=_DELEGATE,
        delegator=_DELEGATOR,
        authority=ROOT_AUTHORITY,
        caveats=(Caveat(enforcer=_ENFORCER, terms=_TERMS, args="0x"),),
        salt=42,
        signature=sig,
    )


